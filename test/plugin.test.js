import assert from 'node:assert/strict'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { test } from 'node:test'
import { build, createServer, preview } from 'vite'
import { dynamicAssetEmitter } from '../dist/index.js'

test('serves fresh assets at custom and default development URLs', async () => {
  const root = await mkdtemp(join(tmpdir(), 'dynamic-asset-emitter-dev-'))
  let server
  let invocation = 0
  try {
    await writeFile(join(root, 'index.html'), '<h1>Fallback page</h1>')
    server = await createServer({
      root,
      configFile: false,
      logLevel: 'silent',
      server: { host: '127.0.0.1', port: 0 },
      plugins: [dynamicAssetEmitter([
        {
          fileName: 'generated/theme.json',
          devPath: 'dynamic/theme.json',
          contentType: 'application/json',
          source: () => JSON.stringify({ invocation: ++invocation }),
        },
        {
          fileName: 'generated/bytes.bin',
          source: () => new Uint8Array([0, 128, 255]),
        },
      ])],
    })
    await server.listen()
    const base = server.resolvedUrls.local[0]
    for (const expected of [1, 2]) {
      const response = await fetch(`${base}dynamic/theme.json?refresh=${expected}`)
      assert.equal(response.status, 200)
      assert.equal(response.headers.get('content-type'), 'application/json')
      assert.deepEqual(await response.json(), { invocation: expected })
    }
    const binary = await fetch(`${base}generated/bytes.bin`)
    assert.equal(binary.status, 200)
    assert.equal(binary.headers.get('content-type'), 'application/octet-stream')
    assert.deepEqual([...new Uint8Array(await binary.arrayBuffer())], [0, 128, 255])
    const page = await fetch(base)
    assert.match(await page.text(), /Fallback page/)
  } finally {
    await server?.close()
    await rm(root, { recursive: true, force: true })
  }
})

test('playground builds and previews generated JSON, text, and binary assets', async () => {
  const root = fileURLToPath(new URL('../examples/playground/', import.meta.url))
  const outDir = await mkdtemp(join(tmpdir(), 'dynamic-asset-emitter-playground-'))
  let server
  try {
    await build({ root, logLevel: 'silent', build: { outDir, emptyOutDir: true } })
    server = await preview({
      root,
      logLevel: 'silent',
      build: { outDir },
      preview: { host: '127.0.0.1', port: 0 },
    })
    const base = server.resolvedUrls.local[0]
    const theme = await fetch(`${base}generated/theme.json`)
    assert.equal(theme.status, 200)
    assert.match(theme.headers.get('content-type'), /^application\/json/)
    const data = await theme.json()
    assert.equal(data.title, 'Hello from the dynamic asset plugin')
    assert.equal(data.invocation, 1)
    assert.ok(Number.isFinite(Date.parse(data.generatedAt)))
    assert.deepEqual(await (await fetch(`${base}generated/theme.json?again=1`)).json(), data)
    const message = await fetch(`${base}generated/message.txt`)
    assert.match(message.headers.get('content-type'), /^text\/plain/)
    assert.match(await message.text(), /^Generated by the plugin at /)
    const binary = await fetch(`${base}generated/bytes.bin`)
    assert.equal(binary.headers.get('content-type'), 'application/octet-stream')
    assert.deepEqual([...new Uint8Array(await binary.arrayBuffer())], [0, 1, 2, 127, 128, 255])
    assert.match(await (await fetch(base)).text(), /Dynamic asset emitter playground/)
  } finally {
    await server?.close()
    await rm(outDir, { recursive: true, force: true })
  }
})

test('writes a dynamic asset to the Vite build output', async () => {
  const root = await mkdtemp(join(tmpdir(), 'dynamic-asset-emitter-'))

  try {
    await writeFile(join(root, 'index.html'), '<h1>Test</h1>')

    await build({
      root,
      configFile: false,
      logLevel: 'silent',
      plugins: [
        dynamicAssetEmitter([
          { fileName: 'static/example.txt', source: () => 'hello from the plugin' },
        ]),
      ],
    })

    assert.equal(
      await readFile(join(root, 'dist/static/example.txt'), 'utf8'),
      'hello from the plugin',
    )
  } finally {
    await rm(root, { recursive: true, force: true })
  }
})
