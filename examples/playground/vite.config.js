import { defineConfig } from 'vite'
import { dynamicAssetEmitter } from 'vite-plugin-dynamic-asset-emitter'

let requests = 0

export default defineConfig({
  plugins: [
    dynamicAssetEmitter([
      {
        devPath: '/dynamic/theme.json',
        fileName: 'generated/theme.json',
        contentType: 'application/json',
        source: () => JSON.stringify({
          title: 'Hello from the dynamic asset plugin',
          color: '#6366f1',
          generatedAt: new Date().toISOString(),
          invocation: ++requests,
        }, null, 2),
      },
      {
        fileName: 'generated/message.txt',
        contentType: 'text/plain; charset=utf-8',
        source: () => `Generated by the plugin at ${new Date().toISOString()}\n`,
      },
      {
        fileName: 'generated/bytes.bin',
        source: () => new Uint8Array([0, 1, 2, 127, 128, 255]),
      },
    ]),
  ],
})
