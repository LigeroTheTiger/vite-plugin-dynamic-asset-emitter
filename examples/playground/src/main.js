import './style.css'

const assets = [
  {
    name: 'JSON with a separate development URL',
    path: import.meta.env.DEV ? '/dynamic/theme.json' : '/generated/theme.json',
    type: 'application/json',
    read: async (response) => {
      const theme = await response.json()
      if (!theme.title || !theme.generatedAt || !Number.isInteger(theme.invocation)) {
        throw new Error('Unexpected theme data')
      }
      return JSON.stringify(theme, null, 2)
    },
  },
  {
    name: 'Text using the default development URL',
    path: '/generated/message.txt',
    type: 'text/plain',
    read: async (response) => {
      const text = await response.text()
      if (!text.startsWith('Generated by the plugin at ')) throw new Error('Unexpected text')
      return text
    },
  },
  {
    name: 'Binary with the default content type',
    path: '/generated/bytes.bin',
    type: 'application/octet-stream',
    read: async (response) => {
      const bytes = [...new Uint8Array(await response.arrayBuffer())]
      if (bytes.join(',') !== '0,1,2,127,128,255') throw new Error('Unexpected binary data')
      return `Bytes: ${bytes.join(', ')}`
    },
  },
]

document.querySelector('#mode').textContent = import.meta.env.DEV
  ? 'Development: fetch again to see fresh timestamps and an increasing JSON invocation count.'
  : 'Build preview: assets were generated during the build. Fetching again should return the same data.'

const results = document.querySelector('#results')
const button = document.querySelector('#refresh')
const status = document.querySelector('#status')

async function refresh() {
  button.disabled = true
  status.textContent = 'Fetching…'
  results.replaceChildren()
  let passed = 0

  for (const asset of assets) {
    const card = document.createElement('article')
    const heading = document.createElement('h2')
    heading.textContent = asset.name
    const link = document.createElement('a')
    link.href = asset.path
    link.textContent = asset.path
    link.target = '_blank'
    link.rel = 'noopener'
    const output = document.createElement('pre')
    card.append(heading, link, output)
    results.append(card)

    try {
      const response = await fetch(`${asset.path}?t=${Date.now()}`, { cache: 'no-store' })
      const type = response.headers.get('content-type') ?? ''
      if (!response.ok) throw new Error(`HTTP ${response.status}`)
      if (!type.startsWith(asset.type)) throw new Error(`Unexpected Content-Type: ${type}`)
      output.textContent = `PASS · HTTP ${response.status} · ${type}\n\n${await asset.read(response)}`
      card.dataset.result = 'pass'
      passed++
    } catch (error) {
      output.textContent = `FAIL · ${error.message}`
      card.dataset.result = 'fail'
    }
  }

  status.textContent = `${passed}/${assets.length} assets passed.`
  button.disabled = false
}

button.addEventListener('click', refresh)
refresh()
